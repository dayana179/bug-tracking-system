    <div class="alert alert-error">

        <strong>Please correct the following errors:</strong>

        <ul>
            <?php foreach ($errors as $error): ?>

                <li><?= e($error) ?></li>

            <?php endforeach; ?>
        </ul>

    </div>

<?php endif; ?>


<div class="card form-card">

    <h2>Bug Report Details</h2>

