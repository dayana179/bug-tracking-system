<?php

// Start the session for CSRF protection
session_start();

// Connect to the database
require_once 'config/database.php';

// Page title
$pageTitle = 'Report Bug';

// Create a CSRF token if one does not exist
if (empty($_SESSION['csrf_token'])) {
    $_SESSION['csrf_token'] = bin2hex(random_bytes(32));
}

// Store form values and validation errors
$errors = [];
$title = '';
$description = '';
$priority = '';

// Check whether the form was submitted
if ($_SERVER['REQUEST_METHOD'] === 'POST') {

    // Retrieve submitted values
    $title = is_string($_POST['title'] ?? null)
        ? trim($_POST['title'])
        : '';

    $description = is_string($_POST['description'] ?? null)
        ? trim($_POST['description'])
        : '';

    $priority = is_string($_POST['priority'] ?? null)
        ? $_POST['priority']
        : '';

    // ----------------------------------
    // 1. CSRF TOKEN VALIDATION
    // ----------------------------------

    $submittedToken = $_POST['csrf_token'] ?? '';

    if (
        !is_string($submittedToken) ||
        !hash_equals($_SESSION['csrf_token'], $submittedToken)
    ) {
        $errors[] = 'Invalid form submission. Please refresh the page and try again.';
    }

    // ----------------------------------
    // 2. TITLE VALIDATION
    // ----------------------------------

    if ($title === '') {
        $errors[] = 'Bug title is required.';
    } else {
        $titleLength = function_exists('mb_strlen')
            ? mb_strlen($title, 'UTF-8')
            : strlen($title);

        if ($titleLength > 150) {
            $errors[] = 'Bug title must not exceed 150 characters.';
        }
    }

    // ----------------------------------
    // 3. DESCRIPTION VALIDATION
    // ----------------------------------

    if ($description === '') {
        $errors[] = 'Bug description is required.';
    } else {
        $descriptionLength = function_exists('mb_strlen')
            ? mb_strlen($description, 'UTF-8')
            : strlen($description);

        if ($descriptionLength > 5000) {
            $errors[] = 'Description must not exceed 5000 characters.';
        }
    }

    // ----------------------------------
    // 4. PRIORITY VALIDATION
    // ----------------------------------

    $allowedPriorities = ['Low', 'Medium', 'High'];

    if (!in_array($priority, $allowedPriorities, true)) {
        $errors[] = 'Please select a valid priority.';
    }

    // ----------------------------------
    // 5. SAVE THE BUG IF VALID
    // ----------------------------------

    if (empty($errors)) {

        try {

            // Start a database transaction
            $pdo->beginTransaction();

            // Insert the new bug report
            // Status and date are generated by MySQL defaults
            $insertBug = $pdo->prepare("
                INSERT INTO bugs
                    (title, description, priority)
                VALUES
                    (:title, :description, :priority)
            ");

            $insertBug->execute([
                ':title' => $title,
                ':description' => $description,
                ':priority' => $priority
            ]);

            // Get the ID of the newly created bug
            $bugId = $pdo->lastInsertId();

            // Record the initial Open status in bug history
            $insertHistory = $pdo->prepare("
                INSERT INTO bug_history
                    (bug_id, previous_status, new_status)
                VALUES
                    (:bug_id, NULL, 'Open')
            ");

            $insertHistory->execute([
                ':bug_id' => $bugId
            ]);

            // Commit both database operations
            $pdo->commit();

            // Prevent accidental duplicate submission
            unset($_SESSION['csrf_token']);

            // Redirect to show the success message
            header('Location: report_bug.php?success=1');
            exit;

        } catch (PDOException $e) {

            // Undo database changes if something fails
            if ($pdo->inTransaction()) {
                $pdo->rollBack();
            }

            // Log technical details for the developer
            error_log('Bug report error: ' . $e->getMessage());

            $errors[] = 'Unable to save the bug report. Please try again.';
        }
    }
}

// Load shared website layout
require_once 'includes/header.php';
require_once 'includes/sidebar.php';

?>

